  function setAll(sel, fn) { var els = document.querySelectorAll(sel); for (var i = 0; i < els.length; i++) fn(els[i]); }
  function apply() {
    var s = STRINGS[lang];
    document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
    document.documentElement.setAttribute('data-lang', lang);
    document.title = s.pageTitle;
    setAll('[data-i18n]', function (el) { var k = el.getAttribute('data-i18n'); if (s[k] != null) el.textContent = s[k]; });
    setAll('[data-i18n-alt]', function (el) { var k = el.getAttribute('data-i18n-alt'); if (s[k] != null) el.setAttribute('alt', s[k]); });
    setAll('h2 .alt', function (el) { el.setAttribute('lang', lang === 'zh' ? 'en' : 'zh-Hans'); });
    setAll('[data-src-en]', function (el) {
      el.src = el.getAttribute('data-src-' + lang); el.height = +el.getAttribute('data-h-' + lang);
    });
    $('lang-toggle').setAttribute('aria-pressed', lang === 'zh' ? 'true' : 'false');
    syncHero();
    setAll('[data-i18n-aria]', function (el) { var k = el.getAttribute('data-i18n-aria'); if (s[k] != null) el.setAttribute('aria-label', s[k]); });
  }
  function save() {
    try { var o = readSave(); o.lang = lang; localStorage.setItem(KEY, JSON.stringify(o)); } catch (e) { /* storage blocked: still works */ }
  }
  $('lang-toggle').addEventListener('click', function () { lang = lang === 'zh' ? 'en' : 'zh'; apply(); save(); });

  // ---- cinematic hero video: autoplay muted loop; unmute and pause controls; reduced motion = poster only
  function syncHero() {
    muteBtn.setAttribute('aria-pressed', hv.muted ? 'true' : 'false');
    muteBtn.setAttribute('data-i18n-aria', hv.muted ? 'ariaUnmute' : 'ariaMute');
    pauseBtn.setAttribute('aria-pressed', hv.paused ? 'true' : 'false');
    pauseBtn.setAttribute('data-i18n-aria', hv.paused ? 'ariaPlay' : 'ariaPause');
    var s = STRINGS[lang];
    muteBtn.setAttribute('aria-label', s[muteBtn.getAttribute('data-i18n-aria')]);
    pauseBtn.setAttribute('aria-label', s[pauseBtn.getAttribute('data-i18n-aria')]);
    document.documentElement.classList.toggle('hero-paused', hv.paused);
  }
  var reduce = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (reduce) { hv.removeAttribute('autoplay'); hv.pause(); }
  else { var p = hv.play(); if (p && p.catch) p.catch(function () { syncHero(); }); }
  muteBtn.addEventListener('click', function () {
    hv.muted = !hv.muted;
    if (!hv.muted) { hv.volume = 0.8; if (hv.paused) hv.play(); }
    syncHero();
  });
  pauseBtn.addEventListener('click', function () { if (hv.paused) hv.play(); else hv.pause(); syncHero(); });
  ['play', 'pause', 'volumechange'].forEach(function (ev) { hv.addEventListener(ev, syncHero); });

  // ---- top bar: transparent over the hero, ink after 80 px of scroll
  var bar = $('topbar');
  function onScroll() { bar.classList.toggle('solid', window.scrollY > 80); }
